-- Upgrade the existing PostgreSQL database for budget scopes and manager ownership.
-- Safe to run more than once. Existing annual budgets remain shared Pôle budgets.

CREATE TABLE IF NOT EXISTS direction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL UNIQUE
);

ALTER TABLE budget_annuel
    ADD COLUMN IF NOT EXISTS scope VARCHAR(30) NOT NULL DEFAULT 'POLE';
ALTER TABLE budget_annuel
    ADD COLUMN IF NOT EXISTS direction_id BIGINT;
ALTER TABLE budget_annuel
    ALTER COLUMN scope SET DEFAULT 'POLE';
UPDATE budget_annuel SET scope = 'POLE' WHERE scope IS NULL;

ALTER TABLE consultant
    ADD COLUMN IF NOT EXISTS direction_id BIGINT;
ALTER TABLE consultant
    ADD COLUMN IF NOT EXISTS manager_id BIGINT;

ALTER TABLE demande_approvisionnement
    ADD COLUMN IF NOT EXISTS manager_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'budget_annuel'::regclass AND conname = 'fk_budget_annuel_direction') THEN
        ALTER TABLE budget_annuel ADD CONSTRAINT fk_budget_annuel_direction
            FOREIGN KEY (direction_id) REFERENCES direction(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'consultant'::regclass AND conname = 'fk_consultant_direction') THEN
        ALTER TABLE consultant ADD CONSTRAINT fk_consultant_direction
            FOREIGN KEY (direction_id) REFERENCES direction(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'consultant'::regclass AND conname = 'fk_consultant_manager') THEN
        ALTER TABLE consultant ADD CONSTRAINT fk_consultant_manager
            FOREIGN KEY (manager_id) REFERENCES consultant(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'demande_approvisionnement'::regclass AND conname = 'fk_da_manager') THEN
        ALTER TABLE demande_approvisionnement ADD CONSTRAINT fk_da_manager
            FOREIGN KEY (manager_id) REFERENCES consultant(id);
    END IF;
END $$;

-- Remove the old UNIQUE (annee, code_budget): the same code may exist in a Pôle
-- budget and in one or more direction budgets.
DO $$
DECLARE c RECORD;
BEGIN
    FOR c IN
        SELECT con.conname
        FROM pg_constraint con
        WHERE con.conrelid = 'budget_annuel'::regclass
          AND con.contype = 'u'
          AND (SELECT array_agg(att.attname::text ORDER BY att.attname::text)
               FROM unnest(con.conkey) AS key(attnum)
               JOIN pg_attribute att ON att.attrelid = con.conrelid AND att.attnum = key.attnum)
              = ARRAY['annee', 'code_budget']::text[]
    LOOP
        EXECUTE format('ALTER TABLE budget_annuel DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_budget_pole_annee_code
    ON budget_annuel (annee, code_budget) WHERE scope = 'POLE';
CREATE UNIQUE INDEX IF NOT EXISTS ux_budget_direction_annee_code
    ON budget_annuel (annee, code_budget, direction_id) WHERE scope = 'DIRECTION';

CREATE INDEX IF NOT EXISTS ix_consultant_manager ON consultant (manager_id);
CREATE INDEX IF NOT EXISTS ix_da_manager ON demande_approvisionnement (manager_id);
